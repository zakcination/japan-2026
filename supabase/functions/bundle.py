"""One-file bundle of an Edge Function for the Supabase Dashboard editor (it takes a single index.ts):
the local .mjs modules are inlined in dependency order, without `export` and without their relative imports.
    python3 supabase/functions/bundle.py assistant      → writes supabase/functions/assistant/one_file.ts
src/tests/test_assistant_logic.py checks that the committed bundle is up to date."""
import pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
LOCAL_IMPORT = re.compile(r'^import\s*\{[^}]*\}\s*from\s*"\./([\w-]+\.mjs)";\n', re.M)
LOCAL_IMPORT_SQ = re.compile(r"^import\s*\{[^}]*\}\s*from\s*'\./([\w-]+\.mjs)';\n", re.M)
EXPORT = re.compile(r'^export (?=(?:async )?function |const |let )', re.M)


def _module(d, name, seen, out):
    if name in seen: return
    seen.add(name)
    src = (d / name).read_text(encoding="utf-8")
    for dep in LOCAL_IMPORT_SQ.findall(src) + LOCAL_IMPORT.findall(src):
        _module(d, dep, seen, out)
    body = EXPORT.sub("", LOCAL_IMPORT.sub("", LOCAL_IMPORT_SQ.sub("", src)))
    out.append(f"// ---- {name} (inlined so the dashboard editor needs one file) ----\n{body.rstrip()}\n// ---- end {name} ----\n")


def bundle(fn):
    d = HERE / fn
    index = (d / "index.ts").read_text(encoding="utf-8")
    deps = LOCAL_IMPORT.findall(index)
    mods, seen = [], set()
    for dep in deps: _module(d, dep, seen, mods)
    head = "// GENERATED by supabase/functions/bundle.py from index.ts + its .mjs modules — edit those, then re-run the script.\n"
    body = LOCAL_IMPORT.sub("", index)
    # the inlined modules go right after the last npm/node import
    imports = list(re.finditer(r'^import .*;\n', body, re.M))
    at = imports[-1].end() if imports else 0
    return head + body[:at] + "\n" + "\n".join(mods) + "\n" + body[at:]


if __name__ == "__main__":
    fn = sys.argv[1] if len(sys.argv) > 1 else "assistant"
    (HERE / fn / "one_file.ts").write_text(bundle(fn), encoding="utf-8")
    print("wrote", HERE / fn / "one_file.ts")
